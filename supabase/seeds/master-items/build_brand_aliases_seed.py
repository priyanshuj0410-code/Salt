#!/usr/bin/env python3
"""build_brand_aliases_seed.py — generate the brand_aliases seed migration.

Reads brand_reference.csv (the de-identified brand -> composition/category master) and
emits an idempotent seed for public.brand_aliases (table created in 0051_brand_aliases.sql).
Stdlib only. Regenerate after growing brand_reference.csv:

    python3 build_brand_aliases_seed.py                 # -> ../../migrations/0052_seed_brand_aliases.sql
    python3 build_brand_aliases_seed.py /tmp/check.sql  # write elsewhere (e.g. to verify)

Run the generated file in the Supabase SQL editor AFTER 0051_brand_aliases.sql.
"""
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "brand_reference.csv"
DEFAULT_OUT = HERE.parent.parent / "migrations" / "0052_seed_brand_aliases.sql"
BATCH = 500
VALID_CONF = {"high-verified", "high", "med", "low"}

HEADER = """\
-- 0052: Seed brand_aliases — brand -> composition/category crosswalk (SALT-081).
-- GENERATED by supabase/seeds/master-items/build_brand_aliases_seed.py — edit
-- brand_reference.csv (via build_brand_reference.py), never this file by hand.
-- De-identified brand->molecule facts from a real shop catalogue with all consumer
-- data (stock/qty/pack/codes/prices) stripped. Idempotent: on conflict do nothing.
-- Run in the Supabase SQL editor AFTER 0051_brand_aliases.sql.
"""


def q(s: str) -> str:
    """SQL string literal; double single-quotes. '' stays ''."""
    return "'" + (s or "").replace("'", "''") + "'"


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    rows = list(csv.DictReader(open(SRC)))
    parts = [HEADER]
    for i in range(0, len(rows), BATCH):
        chunk = rows[i:i + BATCH]
        vals = []
        for r in chunk:
            conf = r["confidence"] if r["confidence"] in VALID_CONF else "med"
            vals.append("  (" + ", ".join([
                q(r["brand_key"]), q(r["brand"]), q(r["manufacturer"]),
                q(r["composition"]), q(r["category"]), q(conf),
            ]) + ")")
        parts.append(
            "insert into public.brand_aliases\n"
            "  (brand_key, brand, manufacturer, composition, category, confidence)\nvalues\n"
            + ",\n".join(vals)
            + "\non conflict (brand_key, manufacturer, composition) do nothing;\n"
        )
    out.write_text("\n".join(parts) + "\n")
    nbatch = (len(rows) + BATCH - 1) // BATCH
    print(f"wrote {out}  ({len(rows)} rows, {nbatch} insert batches)")


if __name__ == "__main__":
    main()
